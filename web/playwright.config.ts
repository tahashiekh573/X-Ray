import { defineConfig } from '@playwright/test';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const fixture = (name: string) => join(here, 'e2e', 'fixtures', name);

/**
 * Browser tests use Chrome's fake media devices, so no real camera is needed:
 *  - "app": default fake camera (synthetic pattern, no face) for UI + camera lifecycle tests
 *  - "face": a looped still of a face (MediaPipe's portrait.jpg test asset) for real tracking
 *  - "hand": MediaPipe's thumb_up.jpg test asset for hand tracking
 * Fixtures are generated by `node e2e/fixtures/make-fixtures.mjs` (needs ffmpeg).
 * Set PW_CHANNEL=chromium to use Playwright's bundled browser instead of installed Chrome.
 */
const channel = process.env.PW_CHANNEL ?? 'chrome';
const baseArgs = ['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'];

export default defineConfig({
  testDir: './e2e',
  timeout: 90_000,
  expect: { timeout: 30_000 },
  fullyParallel: false,
  workers: 1,
  reporter: [['list']],
  use: {
    baseURL: 'http://127.0.0.1:5173',
    viewport: { width: 1440, height: 900 },
    permissions: ['camera'],
    trace: 'retain-on-failure',
  },
  webServer: {
    command: 'npm run dev -- --host 127.0.0.1 --strictPort',
    url: 'http://127.0.0.1:5173',
    reuseExistingServer: true,
    timeout: 120_000,
  },
  projects: [
    { name: 'app', testMatch: /app\.spec\.ts/, use: { channel, launchOptions: { args: baseArgs } } },
    {
      name: 'face',
      testMatch: /face\.spec\.ts/,
      use: { channel, launchOptions: { args: [...baseArgs, `--use-file-for-fake-video-capture=${fixture('portrait.y4m')}`] } },
    },
    {
      name: 'hand',
      testMatch: /hand\.spec\.ts/,
      use: { channel, launchOptions: { args: [...baseArgs, `--use-file-for-fake-video-capture=${fixture('thumb_up.y4m')}`] } },
    },
  ],
});
